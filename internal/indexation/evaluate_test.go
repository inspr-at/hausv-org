func dec(t *testing.T, s string) Decimal {
	t.Helper()
	d, err := ParseDecimal(s)
	if err != nil {
		t.Fatal(err)
	}
	return d
}

func fixture(t *testing.T, points ...string) Dataset {
	t.Helper()
	var values []IndexValue
	month := Month("2025-01")
	for _, p := range points {
		values = append(values, IndexValue{Series: VPI2020, Month: month, Value: dec(t, p)})
		month = month.next()
	}
	d, err := NewDataset(values, nil)
	if err != nil {
		t.Fatal(err)
	}
	return d
}

func basicClause() Clause {
	return Clause{Series: VPI2020, BaseMonth: "2025-01", BaseValue: 100 * Unit, AmountCents: 100_000, ThresholdKind: PercentThreshold, Threshold: 5 * Unit}
}

func TestEvaluateThresholds(t *testing.T) {
	cases := []struct {
		name      string
		points    []string
		configure func(*Clause)
		crossed   bool
		month     Month
		change    string
		amount    int64
	}{
		{"full 5 percent jump", []string{"100", "104.9", "105.6"}, nil, true, "2025-03", "5.6", 105600},
		{"not crossed", []string{"100", "104.9"}, nil, false, "", "4.9", 100000},
		{"equality ignored by default", []string{"100", "105"}, nil, false, "", "5", 100000},
		{"equality reaches", []string{"100", "105"}, func(c *Clause) { c.Crossing = Reaches }, true, "2025-02", "5", 105000},
		{"downward full jump", []string{"100", "96", "94.4"}, nil, true, "2025-03", "-5.6", 94400},
		{"downward equality ignored", []string{"100", "95"}, nil, false, "", "-5", 100000},
		{"excess percent up", []string{"100", "106"}, func(c *Clause) { c.ChangeMode = ExcessChange }, true, "2025-02", "6", 101000},
		{"excess percent down", []string{"100", "94"}, func(c *Clause) { c.ChangeMode = ExcessChange }, true, "2025-02", "-6", 99000},
		{"points full", []string{"200", "206"}, func(c *Clause) { c.BaseValue = 200 * Unit; c.ThresholdKind = PointsThreshold }, true, "2025-02", "3", 103000},
		{"points excess", []string{"200", "206"}, func(c *Clause) {
			c.BaseValue = 200 * Unit
			c.ThresholdKind = PointsThreshold
			c.ChangeMode = ExcessChange
		}, true, "2025-02", "3", 100500},
		{"points excess down", []string{"200", "194"}, func(c *Clause) {
			c.BaseValue = 200 * Unit
			c.ThresholdKind = PointsThreshold
			c.ChangeMode = ExcessChange
		}, true, "2025-02", "-3", 99500},
		{"minimum jump waits without resetting", []string{"100", "105.1", "106"}, func(c *Clause) { c.MinimumChangeCents = 6000 }, true, "2025-03", "6", 106000},
		{"minimum jump symmetric", []string{"100", "94.9", "94"}, func(c *Clause) { c.MinimumChangeCents = 6000 }, true, "2025-03", "-6", 94000},
		{"indices round to one decimal", []string{"100", "105.049"}, nil, false, "", "5", 100000},
		{"index half rounds up", []string{"100", "105.05"}, nil, true, "2025-02", "5.1", 105100},
		{"zero threshold unchanged", []string{"100", "100"}, func(c *Clause) { c.Threshold = 0; c.Crossing = Reaches }, false, "", "0", 100000},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			clause := basicClause()
			if tc.configure != nil {
				tc.configure(&clause)
			}
			data := fixture(t, tc.points...)
			original := clause
			result, err := Evaluate(clause, data, "2025-03")
			if err != nil {
				t.Fatal(err)
			}
			if result.Crossed != tc.crossed || result.TriggerMonth != tc.month || result.ChangePercent != dec(t, tc.change) || result.NewAmountCents != tc.amount {
				t.Fatalf("unexpected result: %+v", result)
			}
			if clause != original {
				t.Fatal("input mutated")
			}
			if tc.crossed && (result.NextClause.BaseMonth != tc.month || result.NextClause.AmountCents != tc.amount || result.Explanation[len(result.Explanation)-1].Code != "base_reset") {
				t.Fatal("jump lost base reset evidence")
			}
		})
	}
}

// Expected values are transcribed from the official calculator handbook, pages
// 7-12, not generated by this implementation. See docs/wertsicherung-berechnung.md.
func TestPublishedCalculatorExamples(t *testing.T) {
	snapshot, err := LoadSnapshot()
	if err != nil {
		t.Fatal(err)
	}
	base, _, _ := snapshot.Data.Lookup(VPI2015, "2016-01")
	current, _, _ := snapshot.Data.Lookup(VPI2015, "2022-12")
	change, amount, err := Revalue(50000, base.Value, current.Value)
	if err != nil || change != dec(t, "25.9") || amount != 62950 {
		t.Fatalf("handbook example 1: %v %v %v", change, amount, err)
	}
	base, _, _ = snapshot.Data.Lookup(VPI2010, "2020-01")
	clause := Clause{Series: VPI2010, BaseMonth: "2020-01", BaseValue: base.Value, AmountCents: 100000, ThresholdKind: PercentThreshold, Threshold: 5 * Unit, Crossing: Reaches}
	for _, tc := range []struct {
		asOf    Month
		crossed bool
		trigger Month
		percent string
		amount  int64
	}{
		{"2021-10", false, "", "4.7", 100000},
		{"2021-11", true, "2021-11", "5.5", 105500},
		{"2022-05", false, "", "4.9", 105500},
		{"2022-06", true, "2022-06", "6.4", 112252},
	} {
		result, err := Evaluate(clause, snapshot.Data, tc.asOf)
		if err != nil || result.Crossed != tc.crossed || result.TriggerMonth != tc.trigger || result.ChangePercent != dec(t, tc.percent) || result.NewAmountCents != tc.amount {
			t.Fatalf("handbook at %s: %+v %v", tc.asOf, result, err)
		}
		clause = result.NextClause
	}
}

func TestEvaluateStopsAtFirstJumpAndResets(t *testing.T) {
	data := fixture(t, "100", "106", "109", "112")
	first, err := Evaluate(basicClause(), data, "2025-04")
	if err != nil || first.TriggerMonth != "2025-02" || first.NewBase != 106*Unit {
		t.Fatalf("first: %+v %v", first, err)
	}
	second, err := Evaluate(first.NextClause, data, "2025-04")
	// 112/106 = 1.05660377 -> 5.7%; €1,060 * 1.057 = €1,120.42.
	if err != nil || second.TriggerMonth != "2025-04" || second.NewAmountCents != 112042 {
		t.Fatalf("second: %+v %v", second, err)
	}
	unchanged, err := Evaluate(second.NextClause, data, "2025-04")
	if err != nil || unchanged.Crossed || unchanged.NewAmountCents != 112042 {
		t.Fatalf("repeated evaluation: %+v %v", unchanged, err)
	}
}

func TestEvaluationRejectsIncompleteOrUnfinalData(t *testing.T) {
	values := fixture(t, "100", "106", "112").Values()
	values[1].Preliminary = true
	data, _ := NewDataset(values, nil)
	result, err := Evaluate(basicClause(), data, "2025-03")
	if err != nil || result.Crossed || result.PendingMonth != "2025-02" || result.EvaluatedThrough != "2025-01" {
		t.Fatalf("preliminary skipped: %+v %v", result, err)
	}
	data, _ = NewDataset([]IndexValue{values[0], values[2]}, nil)
	if _, err = Evaluate(basicClause(), data, "2025-03"); err == nil {
		t.Fatal("missing intermediate month accepted")
	}
	for _, mutate := range []func(*Clause){
		func(c *Clause) { c.BaseValue++ },
		func(c *Clause) { c.BaseMonth = "2025-99" },
		func(c *Clause) { c.Series = "unknown" },
		func(c *Clause) { c.Threshold = -1 },
		func(c *Clause) { c.ThresholdKind = "unknown" },
		func(c *Clause) { c.ChangeMode = "unknown" },
		func(c *Clause) { c.Crossing = "unknown" },
		func(c *Clause) { c.AmountCents = -1 },
	} {
		clause := basicClause()
		mutate(&clause)
		if _, err := Evaluate(clause, fixture(t, "100", "106"), "2025-02"); err == nil {
			t.Fatalf("invalid clause accepted: %+v", clause)
		}
	}
	values[0].Preliminary = true
	data, _ = NewDataset(values, nil)
	if _, err := Evaluate(basicClause(), data, "2025-03"); err == nil {
		t.Fatal("preliminary base accepted")
	}
}

func TestArithmeticOverflowAndRounding(t *testing.T) {
	for _, s := range []string{"1e3", "NaN", "1.1234567", "1,000.3", "--1", ".5", "1.", "9223372036854775807"} {
		if _, err := ParseDecimal(s); err == nil {
			t.Fatalf("invalid decimal accepted: %s", s)
		}
	}
	for _, s := range []string{"-1.25", "0.0", "100.123456"} {
		if got := dec(t, s).String(); got != s {
			t.Errorf("decimal roundtrip %s -> %s", s, got)
		}
	}
	if got := Decimal(math.MinInt64).String(); got != "-9223372036854.775808" {
		t.Fatal(got)
	}
	if _, _, err := Revalue(math.MaxInt64, 100*Unit, 200*Unit); err == nil {
		t.Fatal("money overflow accepted")
	}
	if _, _, err := Revalue(100, 0, Unit); err == nil {
		t.Fatal("zero base accepted")
	}
	if _, amount, err := Revalue(101, 100*Unit, 150*Unit); err != nil || amount != 152 {
		t.Fatalf("contractual half-cent: %d %v", amount, err)
	}
	for _, s := range []string{"", "2026-13", "2026-1", "0000-01"} {
		if _, err := ParseMonth(s); err == nil {
			t.Fatalf("invalid month accepted: %s", s)
		}
	}
}

func TestEvaluateReferenceDoesNotTriggerOnInterveningMonth(t *testing.T) {
	data, err := NewDataset([]IndexValue{{Series: VPI2020, Month: "2025-09", Value: 100 * Unit}, {Series: VPI2020, Month: "2025-10", Value: 150 * Unit}, {Series: VPI2020, Month: "2025-12", Value: 102 * Unit}}, nil)
	if err != nil {
		t.Fatal(err)
	}
	clause := Clause{Series: VPI2020, BaseMonth: "2025-09", BaseValue: 100 * Unit, AmountCents: 100000, ThresholdKind: PercentThreshold, PercentRounding: UnroundedPercent}
	result, err := EvaluateReference(clause, data, "2025-12")
	if err != nil || result.NewAmountCents != 102000 || result.TriggerMonth != "2025-12" {
		t.Fatal(result, err)
	}
}
